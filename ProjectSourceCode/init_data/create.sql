-- VAZLR schema (PostgreSQL)
-- Postgres runs it automatically on first startup when the data volume is empty. 
-- Tables are created in dependency order, and every statement is safe to run again (IF NOT EXISTS).
-- Note: IF NOT EXISTS skips a table that already exists, so it will NOT apply column
-- changes to an existing table. After editing this file, run: docker-compose down -v

-- ---------------------------------------------------------------------------
-- users: login for everyone (volunteers, organizations and the single admin)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE,            -- lowercase it in the app before inserting
    password_hash TEXT NOT NULL,                   -- bcrypt/argon2 hash, never the password
    role          TEXT NOT NULL
                  CHECK (role IN ('volunteer', 'organization', 'admin')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- At most one admin account can exist.
CREATE UNIQUE INDEX IF NOT EXISTS one_admin
    ON users (role) WHERE role = 'admin';

-- ---------------------------------------------------------------------------
-- volunteers: profile for users with role 'volunteer'
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS volunteers (
    user_id    INT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    first_name TEXT NOT NULL,
    last_name  TEXT NOT NULL,
    phone      VARCHAR(20),
    city       TEXT,
    zip        VARCHAR(10)
);

-- ---------------------------------------------------------------------------
-- organizations: profile for users with role 'organization'
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS organizations (
    user_id     INT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    name        VARCHAR(150) NOT NULL,
    description TEXT,
    website     TEXT,
    city        TEXT,
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,    -- drives the "verified" tag
    verified_at TIMESTAMPTZ,
    -- verified_at is set exactly when is_verified is true
    CHECK (is_verified = (verified_at IS NOT NULL))
);

-- ---------------------------------------------------------------------------
-- categories: the cause an event supports (used by the search filter)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categories (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------------
-- events: volunteering events posted by organizations
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS events (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id INT NOT NULL REFERENCES organizations (user_id) ON DELETE RESTRICT,
    category_id     INT NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    title           VARCHAR(150) NOT NULL,
    description     TEXT NOT NULL,
    image_url       TEXT,                          -- path or URL of the event picture
    address         TEXT NOT NULL,
    city            TEXT NOT NULL,
    zip             VARCHAR(10) NOT NULL,
    start_time      TIMESTAMPTZ NOT NULL,
    end_time        TIMESTAMPTZ NOT NULL,
    capacity        INT NOT NULL CHECK (capacity > 0),
    -- "full" is not stored: compare capacity with the count of confirmed bookings
    status          TEXT NOT NULL DEFAULT 'open'
                    CHECK (status IN ('open', 'cancelled', 'completed')),
    CHECK (end_time > start_time)
);

CREATE INDEX IF NOT EXISTS events_start_time_idx      ON events (start_time);
CREATE INDEX IF NOT EXISTS events_category_id_idx     ON events (category_id);
CREATE INDEX IF NOT EXISTS events_city_idx            ON events (city);
CREATE INDEX IF NOT EXISTS events_organization_id_idx ON events (organization_id);

-- ---------------------------------------------------------------------------
-- bookings: a volunteer's sign-up for an event, including the booking form
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bookings (
    id                      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id                INT NOT NULL REFERENCES events (id) ON DELETE CASCADE,
    volunteer_id            INT NOT NULL REFERENCES volunteers (user_id) ON DELETE CASCADE,
    status                  TEXT NOT NULL DEFAULT 'confirmed'
                            CHECK (status IN ('confirmed', 'cancelled', 'waitlisted')),
    emergency_contact_name  TEXT NOT NULL,
    emergency_contact_phone VARCHAR(20) NOT NULL,
    notes                   TEXT,
    waiver_accepted         BOOLEAN NOT NULL DEFAULT FALSE,   -- the app should require true
    booked_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- one booking row per volunteer per event
    UNIQUE (event_id, volunteer_id)
);

CREATE INDEX IF NOT EXISTS bookings_volunteer_id_idx ON bookings (volunteer_id);